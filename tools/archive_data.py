# -*- coding: utf-8 -*-
"""
archive_data.py -- put the irreplaceable data into a GitHub release.

Why this exists
----------------
The Minecraft save is permanently lost (REFACTOR_PLAN §6.1), which makes
``voxel_data/full/overworld.bin`` the *only* source of truth for the whole
project -- and it is not in git (144 MB, over GitHub's 100 MB blob limit, and
.gitignore's "可由存档一键重建" premise died with the save). The built level
(``project/Content/MC`` + ``Maps``) is likewise only on this machine. One disk
failure = the project is unrecoverable.

This uploads two tar.gz assets to a release tagged ``data-backup``:

  * voxel_data.tar.gz     voxel_data/full/*.bin (+ LFS pointers if any)
  * content_level.tar.gz  project/Content/MC + project/Content/Maps
                          (the 10-07/10-08 level, geometry and materials)

Token resolution: ``GH_TOKEN`` / ``GITHUB_TOKEN`` env var, or a ``.gh_token``
file in the repo root (gitignored). Never pass a token as an argument, never
commit it.

Run on the build host (needs no deps beyond stdlib):

    python tools/archive_data.py                 # both archives
    python tools/archive_data.py --only voxel    # just voxel_data
    python tools/archive_data.py --only content  # just the level snapshot

Restoring: tools/restore_data.py.
"""

import argparse
import os
import sys
import tarfile
import tempfile
import urllib.request
import urllib.error
import json

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_SLUG = os.environ.get("MC_REPO_SLUG", "stellarissss/SYFZ-MC2UE5")
TAG = os.environ.get("MC_BACKUP_TAG", "data-backup")
API = "https://api.github.com"


def _say(msg):
    print("[archive_data] %s" % msg)


def load_token():
    for env in ("GH_TOKEN", "GITHUB_TOKEN"):
        if os.environ.get(env):
            return os.environ[env]
    for cand in (os.path.join(REPO, ".gh_token"), ".gh_token"):
        if os.path.isfile(cand):
            with open(cand) as fh:
                tok = fh.read().strip()
            if tok:
                return tok
    _say("no token: set GH_TOKEN or create .gh_token (repo root)")
    return None


def gh(method, path, token, data=None, ctype="application/json"):
    req = urllib.request.Request(
        API + path, data=data, method=method,
        headers={"Authorization": "token %s" % token,
                 "Accept": "application/vnd.github+json",
                 "Content-Type": ctype,
                 "X-GitHub-Api-Version": "2022-11-28"})
    try:
        with urllib.request.urlopen(req) as r:
            body = r.read()
            return r.status, (json.loads(body) if body else {})
    except urllib.error.HTTPError as e:
        try:
            return e.code, json.loads(e.read() or b"{}")
        except Exception:
            return e.code, {}


def ensure_release(token):
    st, rel = gh("GET", "/repos/%s/releases/tags/%s" % (REPO_SLUG, TAG), token)
    if st == 200:
        return rel
    if st == 404:
        st, rel = gh("POST", "/repos/%s/releases" % REPO_SLUG, token,
                     data=json.dumps({
                         "tag_name": TAG,
                         "name": "Data backup (voxel bin + built level)",
                         "body": "Machine-generated by tools/archive_data.py. "
                                 "See docs/REBUILD.md §'Data insurance'."}).encode())
        if st in (200, 201):
            _say("created release %s" % TAG)
            return rel
    _say("release lookup failed: %s %s" % (st, rel.get("message", "")))
    return None


def upload_asset(token, release, path):
    name = os.path.basename(path)
    for a in release.get("assets", []):
        if a["name"] == name:
            st, _ = gh("DELETE",
                       "/repos/%s/releases/assets/%d" % (REPO_SLUG, a["id"]),
                       token)
            _say("deleted stale asset %s (%d)" % (name, st))
            break
    upload_url = release["upload_url"].split("{")[0]
    size = os.path.getsize(path)
    _say("uploading %s (%.1f MB) ..." % (name, size / 1e6))
    req = urllib.request.Request(
        upload_url + "?name=%s" % name, method="POST",
        data=open(path, "rb").read(),
        headers={"Authorization": "token %s" % token,
                 "Content-Type": "application/octet-stream"})
    with urllib.request.urlopen(req) as r:
        _say("  -> %d %s" % (r.status, r.read(120)))
    return True


def make_tar(out_path, roots, hard_limit_gb=1.9):
    total = 0
    with tarfile.open(out_path, "w:gz") as tf:
        for root, arcname in roots:
            if not os.path.isdir(root):
                raise RuntimeError("missing dir: %s" % root)
            for dirpath, _dirs, files in os.walk(root):
                for f in files:
                    full = os.path.join(dirpath, f)
                    total += os.path.getsize(full)
                    tf.add(full, arcname=os.path.join(arcname,
                            os.path.relpath(full, root)))
            _say("  packed %s" % root)
    size = os.path.getsize(out_path)
    if total > hard_limit_gb * 1e9:
        raise RuntimeError("archive exceeds %.1f GB, refusing to upload" %
                           hard_limit_gb)
    _say("  %s: %.1f MB (%.1f MB raw)" % (out_path, size / 1e6, total / 1e6))
    return size


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", choices=("voxel", "content"), default="")
    ap.add_argument("--workdir", default="")
    args = ap.parse_args()

    token = load_token()
    if not token:
        return 1

    work = args.workdir or tempfile.mkdtemp(prefix="mc2ue5_backup_")
    os.makedirs(work, exist_ok=True)

    jobs = []
    if args.only in ("", "voxel"):
        jobs.append(("voxel_data.tar.gz",
                     [(os.path.join(REPO, "voxel_data"), "voxel_data")]))
    if args.only in ("", "content"):
        jobs.append(("content_level.tar.gz",
                     [(os.path.join(REPO, "project/Content/MC"), "Content/MC"),
                      (os.path.join(REPO, "project/Content/Maps"),
                       "Content/Maps")]))
    if not jobs:
        _say("nothing selected")
        return 1

    rel = ensure_release(token)
    if rel is None:
        return 1

    for name, roots in jobs:
        path = os.path.join(work, name)
        make_tar(path, roots)
        upload_asset(token, rel, path)

    _say("done -- restore with tools/restore_data.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
